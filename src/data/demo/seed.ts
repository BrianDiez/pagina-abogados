const appt = (
  id: string,
  clientId: string,
  serviceId: string,
  start: Date,
  durationMin: number,
  status: Appointment["status"],
  extra: Partial<Appointment> = {},
): Appointment => {
  const service = seedServices.find((s) => s.id === serviceId)!;
  const client = seedClients.find((c) => c.id === clientId)!;
  return {
    id,
    lawyerId: service.lawyerId,
    clientId,
    serviceId,
    status,
    startsAt: start.toISOString(),
    endsAt: new Date(start.getTime() + durationMin * 60_000).toISOString(),
    modality: service.modality,
    price: service.price,
    currency: service.currency,
    paymentStatus: status === "pending_payment" ? "pending" : "paid",
    clientName: client.name,
    clientEmail: client.email,
    serviceName: service.name,
    ...extra,
  };
};

